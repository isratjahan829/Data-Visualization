def tab_measurement():
    ct = pd.read_csv(TABLES / "table_reliability_validity.csv", index_col=0)
    ld = pd.read_csv(TABLES / "table_cfa_loadings.csv")
    rows = []
    for fct in FACTOR_ORDER:
        sub = ld[ld.factor == fct]
        r = ct.loc[fct]
        first = True
        for _, it in sub.iterrows():
            lead = (rf"\multirow{{{len(sub)}}}{{*}}{{\parbox{{2.6cm}}{{{FACTORS[fct]['name']} ({fct})}}}}"
                    if first else "")
            stats_ = (rf"\multirow{{{len(sub)}}}{{*}}{{{r.alpha:.3f}}} & \multirow{{{len(sub)}}}{{*}}{{{r.CR:.3f}}} & \multirow{{{len(sub)}}}{{*}}{{{r.AVE:.3f}}}"
                      if first else "& &")
            rows.append(rf"{lead} & {it['item']} & {ITEM_TEXT[it['item']]} & {it.loading:.3f} & {stats_}\\")
            first = False
        rows.append(r"\midrule")
    rows = rows[:-1]
    (OUT / "tab_measurement.tex").write_text(
        r"""\begin{table}[!htbp]
\centering
\caption{Operationalisation of the eight evaluation factors and measurement-model results (standardised CFA loadings $\lambda$, Cronbach's $\alpha$, composite reliability CR, average variance extracted AVE). Items marked (R) are reverse-coded. CFA fit: $\chi^2(\CfaDf)=\ChiSq$, CFI~$=\CFIval$, TLI~$=\TLIval$, RMSEA~$=\RMSEAval$, SRMR~$=\SRMRval$.}
\label{tab:measurement}
\footnotesize
\resizebox{\textwidth}{!}{%
\begin{tabular}{p{2.7cm}lp{7.4cm}cccc}
\toprule
Factor & Item & Wording (abridged) & $\lambda$ & $\alpha$ & CR & AVE \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}}
\end{table}
""")


def tab_htmt():
    H = pd.read_csv(TABLES / "table_htmt.csv", index_col=0)
    ct = pd.read_csv(TABLES / "table_reliability_validity.csv", index_col=0)
    phi = pd.read_csv(TABLES / "table_latent_correlations.csv", index_col=0)
    rows = []
    for i, a in enumerate(FACTOR_ORDER):
        cells = []
        for j, b in enumerate(FACTOR_ORDER):
            if j < i:
                cells.append(f"{H.loc[a, b]:.2f}")
            elif j == i:
                cells.append(rf"\textbf{{{ct.loc[a, 'sqrtAVE']:.2f}}}")
            else:
                cells.append(f"\\textit{{{phi.loc[a, b]:.2f}}}")
        rows.append(f"{a} & " + " & ".join(cells) + r"\\")
    (OUT / "tab_htmt.tex").write_text(
        r"""\begin{table}[!htbp]
\centering
\caption{Discriminant validity. Lower triangle: HTMT ratios; diagonal (bold): $\sqrt{\mathrm{AVE}}$; upper triangle (italic): latent CFA correlations.}
\label{tab:htmt}
\footnotesize
\setlength{\tabcolsep}{3.5pt}
\begin{tabular}{l""" + "c" * len(FACTOR_ORDER) + r"""}
\toprule
 & """ + " & ".join(FACTOR_ORDER) + r"""\\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\end{table}
""")


