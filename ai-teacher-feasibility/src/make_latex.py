        r = ct.loc[fct]
        first = True
        for _, it in sub.iterrows():
            lead = (rf"\multirow{{{len(sub)}}}{{*}}{{\parbox{{2.6cm}}{{{FACTORS[fct]['name']} ({fct})}}}}"
                    if first else "")
