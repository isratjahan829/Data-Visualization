def tab_rules():
    r = pd.read_csv(TABLES / "rules_TRFS.csv")
    ab = {"Low": "L", "Medium": "M", "High": "H"}
    cells = [f"{x.Rule} & {ab[x.PC]} & {ab[x.IQ]} & {ab[x.TW]} & {ab[x.TRFS]}" for x in r.itertuples()]
    third = int(np.ceil(len(cells) / 3))
    cols = [cells[i * third:(i + 1) * third] for i in range(3)]
    rows = []
    for i in range(third):
        parts = [cols[c][i] if i < len(cols[c]) else "& & & &" for c in range(3)]
        rows.append(" & ".join(parts) + r"\\")
    tw = pd.read_csv(TABLES / "rules_TW.csv")
    twg = tw.pivot(index="R", columns="E", values="TW").loc[["Low", "Medium", "High"], ["Low", "Medium", "High"]]
    twrows = [rf"R = {i} & " + " & ".join(twg.loc[i]) + r"\\" for i in twg.index]
    (OUT / "tab_rules.tex").write_text(
        r"""\begin{table}[!htbp]
\centering
\caption{Rule bases of the trust sub-system FIS$_3$ (top) and the final system FIS$_4$ (bottom; L/M/H = Low/Medium/High).}
\label{tab:rules}
\footnotesize
\begin{tabular}{lccc}
\toprule
FIS$_3$: TW & E = Low & E = Medium & E = High\\
\midrule
""" + "\n".join(twrows) + r"""
\bottomrule
\end{tabular}

\vspace{0.6em}
\setlength{\tabcolsep}{3pt}
\begin{tabular}{rcccc|rcccc|rcccc}
\toprule
\# & PC & IQ & TW & TRFS & \# & PC & IQ & TW & TRFS & \# & PC & IQ & TW & TRFS\\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\end{table}
""")


