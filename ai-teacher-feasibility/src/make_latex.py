def f(x, nd=2):
    return f"{x:.{nd}f}"


def pval(p):
    """Table cell form: '<0.001' or '0.123'."""
    return r"$<$0.001" if p < 0.001 else f"{p:.3f}"


def prel(p):
    """In-text relation form, used as $p\\Macro$: '<0.001' or '=0.123'."""
    return "<0.001" if p < 0.001 else f"={p:.3f}"


def macros():
    m = {}
    fl = S["flow"]
    m["Ntotal"] = f"{fl['total_responses']:,}"
    m["Nusers"] = f"{fl['chatgpt_users']:,}"
    m["Nage"] = f"{fl['valid_age_18_100']:,}"
    m["Ncomplete"] = f"{fl['complete_on_model_items']:,}"
    m["Nfinal"] = f"{fl['after_straightlining_removal']:,}"
    m["Nstraight"] = f"{fl['complete_on_model_items'] - fl['after_straightlining_removal']:,}"
    m["Ncountries"] = str(S["n_countries_study"])
    m["AgeMean"] = f(S["age"]["mean"], 1)
    m["AgeSD"] = f(S["age"]["sd"], 1)
    c = S["cfa_fit"]
    m["ChiSq"] = f"{c['chi2']:,.1f}"
    m["CfaDf"] = str(int(c["df"]))
    for k in ("CFI", "TLI", "RMSEA", "SRMR"):
        m[k + "val"] = f(c[k], 3)
    m["HTMTmax"] = f(S["max_htmt"], 2)
    m["Harman"] = f(S["harman_first_factor_pct"], 1)
    t = S["trfs"]
    m["TRFSmean"] = f(t["mean"], 1)
    m["TRFSsd"] = f(t["sd"], 1)
    m["TRFSmedian"] = f(t["median"], 1)
    m["PctHuman"] = f(t["class_pct"]["Human involvement required"], 1)
    m["PctPartial"] = f(t["class_pct"]["Partial AI assistance"], 1)
    m["PctFull"] = f(t["class_pct"]["Full AI replacement"], 1)
    m["KWusageH"] = f"{t['kw_usage_H']:,.1f}"
    m["RhoUsage"] = f(t["rho_usage"], 2)
    for k, v in S["intermediate"].items():
        m[f"{k}mean"] = f(v["mean"], 1)
        m[f"{k}sd"] = f(v["sd"], 1)
    rho = {r["criterion"].split(" ")[0]: r for r in S["trfs_validity"]}
    m["RhoTSI"] = f(rho["TSI"]["spearman_rho"], 2)
    m["RhoSat"] = f(rho["Q24e"]["spearman_rho"], 2)
    m["RhoExp"] = f(rho["Q16"]["spearman_rho"], 2)
    m["RhoUse"] = f(rho["Q15"]["spearman_rho"], 2)
    m["RhoReplace"] = f(rho["Q22h"]["spearman_rho"], 3)
    m["PReplace"] = f(rho["Q22h"]["p"], 2)
    fr = S["activity_friedman"]
    m["FriedmanChi"] = f"{fr['chi2']:,.1f}"
    m["KendallW"] = f(fr["kendall_W"], 3)
    mc = {r["model"]: r for r in S["model_comparison"]}
    keys = {"ANN (MLP)": "Ann", "Hybrid fuzzy-ANN": "Hyb", "Gradient boosting": "Gb",
            "Random forest": "Rf", "Linear regression": "Lr", "SVR (RBF)": "Svr",
            "Fuzzy HFIS (calibrated)": "Fis"}
    for name, k in keys.items():
        r = mc[name]
        m[f"{k}RMSE"] = f(r["RMSE_mean"], 2)
        m[f"{k}MAE"] = f(r["MAE_mean"], 2)
        m[f"{k}Rsq"] = f(r["R2_mean"], 3)
        if name != "ANN (MLP)":
            m[f"{k}P"] = prel(r["p_vs_ANN"])
    m["CVsplits"] = str(S["cv_design"]["splits"])
    m["CVrepeats"] = str(S["cv_design"]["repeats"])
    m["CVfits"] = str(S["cv_design"]["splits"] * S["cv_design"]["repeats"])
    m["FisShare"] = f(100 * mc["Fuzzy HFIS (calibrated)"]["R2_mean"] / mc["ANN (MLP)"]["R2_mean"], 0)
    m["AnnFisRatio"] = f(mc["ANN (MLP)"]["R2_mean"] / mc["Fuzzy HFIS (calibrated)"]["R2_mean"], 1)
    ld = pd.read_csv(TABLES / "table_cfa_loadings.csv")
    m["LoadMin"] = f(np.floor(ld.loading.min() * 100) / 100, 2)
    phi = pd.read_csv(TABLES / "table_latent_correlations.csv", index_col=0)
    m["PhiEmax"] = f(np.ceil(phi.loc["E"].drop("E").abs().max() * 100) / 100, 2)
    m["SurrRsq"] = f(S["ann_surrogate_of_fis"]["R2"], 3)
    m["SurrRMSE"] = f(S["ann_surrogate_of_fis"]["RMSE"], 2)
    m["ImpTau"] = f(S["importance_rank_agreement_tau"], 2)
    rb = S["robustness"]
    m["RobDraws"] = str(rb["draws"])
    m["RobTau"] = f(rb["tau_mean"], 3)
    m["RobTauLow"] = f(rb["tau_p5"], 3)
    m["RobAgree"] = f(100 * rb["category_agreement_mean"], 1)
    m["RobAgreeMin"] = f(100 * rb["category_agreement_min"], 0)
    sg = {r["variable"]: r for r in S["subgroups"]}
    m["EpsMax"] = f(max(r["epsilon2"] for r in S["subgroups"]), 3)
    m["EpsVersion"] = f(sg["Q14"]["epsilon2"], 3)
    imp = {r["factor"]: r for r in S["importance"]}
    for k, r in imp.items():
        m[f"Imp{k}"] = f(r["ann_perm_importance_R2_drop"], 3)
        m[f"Sens{k}"] = f(r["fis_sensitivity_plus1SD"], 2)
        m[f"Rho{k}"] = f(r["spearman_with_TSI"], 2)
    lines = [r"% generated by src/make_latex.py -- do not edit by hand"]
    for k, v in m.items():
        assert k.isalpha(), k
        lines.append(rf"\newcommand{{\{k}}}{{{v}}}")
    lines.append(r"\makeatletter")
    for a in S["activities"]:
        code = a["code"]
        for key, val in [("score", f(a["TRFS_mean"], 1)), ("lo", f(a["ci_low"], 1)),
                         ("hi", f(a["ci_high"], 1)), ("full", f(a["pct_full"], 1)),
                         ("human", f(a["pct_human"], 1)), ("cap", f(a["capability_mean"], 2)),
                         ("rank", str(a["rank"])), ("tier", a["tier"])]:
            lines.append(rf"\expandafter\def\csname act@{code}@{key}\endcsname{{{val}}}")
    lines.append(r"\newcommand{\act}[2]{\csname act@#1@#2\endcsname}")
    lines.append(r"\makeatother")
    (OUT / "macros.tex").write_text("\n".join(lines) + "\n")


