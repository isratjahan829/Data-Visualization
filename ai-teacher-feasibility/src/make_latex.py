def tab_models():
    t = pd.read_csv(TABLES / "table_model_comparison.csv", index_col=0)
    rows = []
    for name, r in t.iterrows():
        p = "--" if name == "ANN (MLP)" else pval(r.p_vs_ANN)
        tt = "--" if name == "ANN (MLP)" else f"{r.t_vs_ANN:.2f}"
        nm = rf"\textbf{{{name}}}" if name == "ANN (MLP)" else name
        rows.append(rf"{nm} & {r.MSE_mean:.1f} ({r.MSE_std:.1f}) & {r.RMSE_mean:.2f} ({r.RMSE_std:.2f}) & "
                    rf"{r.MAE_mean:.2f} ({r.MAE_std:.2f}) & {r.R2_mean:.3f} ({r.R2_std:.3f}) & {tt} & {p}\\")
    (OUT / "tab_models.tex").write_text(
        r"""\begin{table}[!htbp]
\centering
\caption{Out-of-fold prediction of the Teacher Substitution Index (TSI, 0--100) from the eight factors: mean (SD) over \CVsplits-fold cross-validation repeated \CVrepeats{} times (\CVfits{} folds). $t$ and $p$: Nadeau--Bengio corrected resampled $t$-test on fold RMSE against the ANN. The calibrated fuzzy model uses no TSI information except a one-parameter linear rescaling of the TRFS fitted on each training fold.}
\label{tab:models}
\footnotesize
\resizebox{\textwidth}{!}{%
\begin{tabular}{lcccccc}
\toprule
Model & MSE & RMSE & MAE & $R^2$ & $t$ vs ANN & $p$ \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}}
\end{table}
""")


